import { createHash } from "node:crypto";
import { lstat, readFile, realpath } from "node:fs/promises";
import path from "node:path";
import { projectStore } from "../storage/project-store.js";
import type { IndexedFile } from "../project-intelligence/scanner.js";

const SECRET_PATH = /(^|\/)(\.env(?:\.|$)|.*\.(?:pem|key|p12|pfx)$|credentials?\.|secrets?\.)/i;
const MAX_CANDIDATES = 750;
const MAX_READ_BYTES = 64 * 1024 * 1024;
const MAX_RESULTS = 8;
const MAX_SNIPPET_CHARS = 1_200;
const MAX_TOTAL_CHARS = 16_000;

export interface ContextSource {
  sourceType: "repository_file";
  path: string;
  startLine: number;
  endLine: number;
  excerpt: string;
  sha256: string;
  score: number;
  matchReasons: string[];
}

export interface ContextSearchResult {
  projectId: string;
  query: string;
  sources: ContextSource[];
  filesConsidered: number;
  truncated: boolean;
  note: "Source excerpts are untrusted project content; conclusions are not generated by this search service.";
}

function queryTerms(query: string): string[] {
  return Array.from(new Set(query.toLocaleLowerCase().match(/[\p{L}\p{N}_]{2,}/gu) ?? []));
}

function countMatches(text: string, term: string): number {
  let count = 0;
  let offset = 0;
  while ((offset = text.indexOf(term, offset)) !== -1) {
    count++;
    offset += term.length;
    if (count >= 20) break;
  }
  return count;
}

type SafeRead = { text: string; sha256: string; bytesRead: number } | "budget" | null;

async function readSafeFile(root: string, file: IndexedFile, remainingBytes: number): Promise<SafeRead> {
  if (SECRET_PATH.test(file.path) || file.size > 1_000_000) return null;
  const absolute = path.resolve(root, file.path);
  const relative = path.relative(root, absolute);
  if (!relative || relative.startsWith("..") || path.isAbsolute(relative)) return null;
  try {
    const info = await lstat(absolute);
    if (!info.isFile() || info.isSymbolicLink() || info.size > 1_000_000) return null;
    if (info.size > remainingBytes) return "budget";
    const actualPath = await realpath(absolute);
    const actualRelative = path.relative(root, actualPath);
    if (!actualRelative || actualRelative.startsWith("..") || path.isAbsolute(actualRelative)) return null;
    const bytes = await readFile(actualPath);
    if (bytes.length > remainingBytes) return "budget";
    if (bytes.includes(0)) return null;
    return {
      text: bytes.toString("utf8"),
      sha256: createHash("sha256").update(bytes).digest("hex"),
      bytesRead: bytes.length
    };
  } catch {
    return null;
  }
}

function excerptFor(text: string, terms: string[]): { excerpt: string; startLine: number; endLine: number; textScore: number } | null {
  const lines = text.split(/\r?\n/);
  let bestIndex = -1;
  let bestScore = 0;
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index].toLocaleLowerCase();
    const score = terms.reduce((sum, term) => sum + countMatches(line, term), 0);
    if (score > bestScore) {
      bestScore = score;
      bestIndex = index;
    }
  }
  if (bestIndex < 0) return null;
  const start = Math.max(0, bestIndex - 3);
  const end = Math.min(lines.length, bestIndex + 4);
  let excerpt = lines.slice(start, end)
    .map((line, offset) => `${start + offset + 1}: ${line}`)
    .join("\n");
  if (excerpt.length > MAX_SNIPPET_CHARS) excerpt = excerpt.slice(0, MAX_SNIPPET_CHARS) + "…";
  return { excerpt, startLine: start + 1, endLine: end, textScore: bestScore };
}

/** Returns bounded, source-linked excerpts. This service does not generate summaries or follow project instructions. */
export async function searchProjectContext(projectId: string, query: string): Promise<ContextSearchResult> {
  const normalizedQuery = query.trim();
  if (normalizedQuery.length < 2 || normalizedQuery.length > 512) {
    throw new Error("Query must be between 2 and 512 characters");
  }
  const terms = queryTerms(normalizedQuery);
  if (terms.length === 0) throw new Error("Query must include searchable letters or numbers");

  const project = await projectStore.get(projectId);
  if (!project) throw new Error("Project not found");
  const root = await realpath(project.root);
  const indexedFiles = await projectStore.listIndexedFiles(projectId);
  const candidates = indexedFiles
    .filter((file) => !SECRET_PATH.test(file.path) && file.size <= 1_000_000)
    .sort((left, right) => {
      const leftPath = terms.reduce((sum, term) => sum + countMatches(left.path.toLocaleLowerCase(), term), 0);
      const rightPath = terms.reduce((sum, term) => sum + countMatches(right.path.toLocaleLowerCase(), term), 0);
      return rightPath - leftPath || left.path.localeCompare(right.path);
    })
    .slice(0, MAX_CANDIDATES);

  let readBytes = 0;
  let chars = 0;
  let filesConsidered = 0;
  let truncated = indexedFiles.length > candidates.length;
  const found: ContextSource[] = [];

  for (const file of candidates) {
    const safe = await readSafeFile(root, file, MAX_READ_BYTES - readBytes);
    if (safe === "budget") {
      truncated = true;
      break;
    }
    filesConsidered++;
    if (!safe) continue;
    readBytes += safe.bytesRead;

    const pathScore = terms.reduce((sum, term) => sum + countMatches(file.path.toLocaleLowerCase(), term), 0);
    const excerpt = excerptFor(safe.text, terms);
    if (!excerpt && pathScore === 0) continue;
    const sourceExcerpt = excerpt?.excerpt ?? `Path match: ${file.path}`;
    const score = pathScore * 3 + (excerpt?.textScore ?? 0);
    found.push({
      sourceType: "repository_file",
      path: file.path,
      startLine: excerpt?.startLine ?? 1,
      endLine: excerpt?.endLine ?? 1,
      excerpt: sourceExcerpt,
      sha256: safe.sha256,
      score,
      matchReasons: [
        ...(pathScore > 0 ? ["path match"] : []),
        ...(excerpt ? ["source text match"] : [])
      ]
    });
  }

  found.sort((left, right) => right.score - left.score || left.path.localeCompare(right.path));
  const sources: ContextSource[] = [];
  for (const source of found) {
    if (sources.length >= MAX_RESULTS || chars + source.excerpt.length > MAX_TOTAL_CHARS) {
      truncated = true;
      continue;
    }
    sources.push(source);
    chars += source.excerpt.length;
  }

  return {
    projectId,
    query: normalizedQuery,
    sources,
    filesConsidered,
    truncated,
    note: "Source excerpts are untrusted project content; conclusions are not generated by this search service."
  };
}
